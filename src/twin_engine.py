# Shared clinical safety threshold (reused across all modules)
HYPOGLYCEMIA_THRESHOLD_MG_DL: float = 70.0


def get_low_glucose_safety_alert(glucose: Optional[float], timestamp: Optional[str] = None) -> Optional[str]:
    """
    Evaluates rule-based low-glucose safety alert strictly on measured glucose readings.
    Never uses predicted or hypothetical values.
    Returns None if glucose is missing, NaN, or >= 70.0 mg/dL.
    """
    if glucose is None:
        return None
    try:
        val = float(glucose)
    except (ValueError, TypeError):
        return None
    if np.isnan(val):
        return None
    if val < HYPOGLYCEMIA_THRESHOLD_MG_DL:
        t_str = str(timestamp) if timestamp else "latest reading"
        return (
            f"Low glucose reading: the measured value of {val:.1f} mg/dL (at {t_str}) is below 70 mg/dL. "
            f"This alert is based on the measured reading, not the ML prediction. This is synthetic data. "
            f"If this were a real reading, follow your clinician's guidance and seek medical help if you have symptoms."
        )
    return None



class TwinEngine:
    """
    Inference and Simulation Engine for TwinSense AI.
    Loads trained artifacts and provides validated inference and what-if simulation.
    """

    def __init__(self, model_path: Path = None, feature_cols_path: Path = None):
        # Resolve paths: use config-selected paths by default, allow override
        if model_path is None:
            model_path = _ACTIVE_MODEL_PATH
        if feature_cols_path is None:
            feature_cols_path = _ACTIVE_FEATURE_COLS_PATH

        if not model_path.exists():
            raise FileNotFoundError(f"Model file not found at: {model_path}. Please run train.py first.")
        if not feature_cols_path.exists():
            raise FileNotFoundError(f"Feature columns schema not found at: {feature_cols_path}.")

        self.model = joblib.load(model_path)
        with open(feature_cols_path, "r", encoding="utf-8") as f:
            schema = json.load(f)
            self.expected_feature_columns = schema["feature_columns"]

        # Record which version is active
        self.active_model_version = _MODEL_VERSION
        self.is_v2 = _IS_V2
        # Select hypoglycemia warning based on active model
        self.hypoglycemia_warning = V2_HYPOGLYCEMIA_WARNING if self.is_v2 else UNSUPPORTED_HYPOGLYCEMIA_WARNING

    def validate_inputs(self, baseline_profile: dict, recent_readings: pd.DataFrame) -> pd.DataFrame:
        """
        Validates patient profile and time-series telemetry.
        Raises ValueError if fields are missing or values are invalid.
        Returns a sorted, validated copy of recent_readings.
        """
        # 1. Validate Baseline Profile
        if not isinstance(baseline_profile, dict):
            raise ValueError(f"baseline_profile must be a dictionary, received {type(baseline_profile)}")
        for field in REQUIRED_BASELINE_FIELDS:
            if field not in baseline_profile or baseline_profile[field] is None:
                raise ValueError(f"Missing required baseline profile field: '{field}'")
            val = baseline_profile[field]
            if not isinstance(val, (int, float, np.number)) or np.isnan(val):
                raise ValueError(f"Field '{field}' must be a valid number, got: {val}")

        if baseline_profile["age"] <= 0 or baseline_profile["age"] > 125:
            raise ValueError(f"Invalid age: {baseline_profile['age']}")
        if baseline_profile["bmi"] < 10.0 or baseline_profile["bmi"] > 80.0:
            raise ValueError(f"Invalid BMI: {baseline_profile['bmi']}")
        if baseline_profile["baseline_hba1c"] < 3.0 or baseline_profile["baseline_hba1c"] > 25.0:
            raise ValueError(f"Invalid baseline_hba1c: {baseline_profile['baseline_hba1c']}")
        if baseline_profile["diabetes_duration_years"] < 0:
            raise ValueError(f"Invalid diabetes_duration_years: {baseline_profile['diabetes_duration_years']}")

        # 2. Validate Recent Readings
        if not isinstance(recent_readings, pd.DataFrame):
            raise ValueError(f"recent_readings must be a pandas DataFrame, received {type(recent_readings)}")

        for col in REQUIRED_READING_COLUMNS:
            if col not in recent_readings.columns:
                raise ValueError(f"Missing required column '{col}' in recent_readings DataFrame")

        if len(recent_readings) < MINIMUM_READINGS_REQUIRED:
            raise ValueError(
                f"Insufficient reading history: Received {len(recent_readings)} rows, but at least "
                f"{MINIMUM_READINGS_REQUIRED} consecutive 5-minute readings (30 minutes) are required."
            )

        # Copy and parse timestamps
        df = recent_readings.copy()
        try:
            df["timestamp"] = pd.to_datetime(df["timestamp"])
        except Exception as e:
            raise ValueError(f"Failed to parse timestamps in recent_readings: {e}")

        # Check chronological ordering
        if not df["timestamp"].is_monotonic_increasing:
            raise ValueError("Timestamps in recent_readings must be strictly sorted in chronological order.")

        # Check for duplicate timestamps
        if df["timestamp"].duplicated().any():
            raise ValueError("Duplicate timestamps found in recent_readings.")

        # Validate physiological simulation bounds
        glucose_vals = df["glucose_mg_dl"].values
        if np.isnan(glucose_vals).any():
            raise ValueError("Null or NaN values detected in glucose_mg_dl.")
        if (glucose_vals < 30.0).any() or (glucose_vals > 500.0).any():
            raise ValueError(f"Glucose readings contain values outside allowable bounds (30-500 mg/dL).")

        return df

    def extract_features(self, baseline_profile: dict, validated_readings: pd.DataFrame) -> pd.DataFrame:
        """
        Calculates exact 11 past-only features matching training schema and ordering.
        """
        # Ensure we look at the last 6 readings for 30m window
        window_df = validated_readings.iloc[-MINIMUM_READINGS_REQUIRED:].copy()

        # Current reading (at index -1)
        current_glucose = float(window_df["glucose_mg_dl"].iloc[-1])
        current_meal = int(window_df["meal_event"].iloc[-1])

        # Past 15 minutes (last 3 readings: t-10m, t-5m, t)
        past_15m_glucose = window_df["glucose_mg_dl"].iloc[-3:]
        past_15m_hr = window_df["heart_rate"].iloc[-3:]
        past_15m_steps = window_df["steps"].iloc[-3:]

        glucose_mean_15m = float(past_15m_glucose.mean())
        heart_rate_mean_15m = float(past_15m_hr.mean())
        steps_sum_15m = float(past_15m_steps.sum())

        # Past 30 minutes (all 6 readings in window: t-25m to t)
        glucose_mean_30m = float(window_df["glucose_mg_dl"].mean())

        # Glucose change over past 15 minutes: reading(t) - reading(t - 15m)
        # In a 6-reading window: index -1 is t, index -4 is t - 15m (3 steps back)
        glucose_change_15m = float(window_df["glucose_mg_dl"].iloc[-1] - window_df["glucose_mg_dl"].iloc[-4])

        # Construct dictionary of features
        feature_dict = {
            "current_glucose_mg_dl": current_glucose,
            "glucose_mean_past_15m": glucose_mean_15m,
            "glucose_mean_past_30m": glucose_mean_30m,
            "glucose_change_past_15m": glucose_change_15m,
            "heart_rate_mean_past_15m": heart_rate_mean_15m,
            "steps_sum_past_15m": steps_sum_15m,
            "current_meal_event": current_meal,
            "age": float(baseline_profile["age"]),
            "bmi": float(baseline_profile["bmi"]),
            "baseline_hba1c": float(baseline_profile["baseline_hba1c"]),
            "diabetes_duration_years": float(baseline_profile["diabetes_duration_years"])
        }

        # Build single-row DataFrame strictly ordered according to expected schema
        feature_df = pd.DataFrame([feature_dict])[self.expected_feature_columns]
        return feature_df

    def predict_risk(self, baseline_profile: dict, recent_readings: pd.DataFrame) -> dict:
        """
        Primary Digital Twin risk inference function.
        Returns full structured telemetry, prediction, probabilities, factors, and disclaimers.
        """
        validated_df = self.validate_inputs(baseline_profile, recent_readings)
        feature_df = self.extract_features(baseline_profile, validated_df)

        # Model inference
        predicted_class = int(self.model.predict(feature_df)[0])
        model_classes = list(self.model.classes_)
        raw_probs = self.model.predict_proba(feature_df)[0]

        # Map probabilities safely (highlighting class 1 is unsupported)
        prob_dict = {
            "1_hypoglycemia": 0.0,  # Explicit 0.0 with limitation notice
            "2_in_range": 0.0,
            "3_hyperglycemia": 0.0
        }
        for cls_id, prob in zip(model_classes, raw_probs):
            if cls_id == 2:
                prob_dict["2_in_range"] = round(float(prob), 4)
            elif cls_id == 3:
                prob_dict["3_hyperglycemia"] = round(float(prob), 4)
            elif cls_id == 1:
                prob_dict["1_hypoglycemia"] = round(float(prob), 4)

        current_time = validated_df["timestamp"].iloc[-1]
        target_time = current_time + pd.Timedelta(minutes=PREDICTION_HORIZON_MINUTES)
        current_glucose = float(validated_df["glucose_mg_dl"].iloc[-1])
        delta_15m = float(feature_df["glucose_change_past_15m"].iloc[0])

        # Evaluate target range status (70 - 180 mg/dL)
        is_in_target = bool(70.0 <= current_glucose <= 180.0)
        current_glucose_caution = None
        if not is_in_target:
            if current_glucose < 70.0:
                current_glucose_caution = (
                    f"Caution: Current observed glucose ({current_glucose:.1f} mg/dL) is below the configured "
                    f"target range (70–180 mg/dL). A reassuring AI forecast does NOT override an out-of-range reading."
                )
            else:
                current_glucose_caution = (
                    f"Caution: Current observed glucose ({current_glucose:.1f} mg/dL) is above the configured "
                    f"target range (70–180 mg/dL). A reassuring AI forecast does NOT override an out-of-range reading."
                )

        # Check telemetry staleness / gaps (expected 5-min intervals)
        intervals = validated_df["timestamp"].diff().dropna().dt.total_seconds()
        is_stale = bool((intervals > 15 * 60).any())

        # Identify key observed factors (neutral, non-prescriptive, no treatment recommendations)
        contributing_factors = []
        if current_glucose_caution:
            contributing_factors.append(current_glucose_caution)
        contributing_factors.extend([
            f"Current observed glucose is {current_glucose:.1f} mg/dL.",
            f"Recent 15-minute glucose trajectory changed by {delta_15m:+.1f} mg/dL.",
            f"Rolling 30-minute average glucose is {feature_df['glucose_mean_past_30m'].iloc[0]:.1f} mg/dL.",
            f"Patient baseline HbA1c is {baseline_profile['baseline_hba1c']:.1f}% with BMI {baseline_profile['bmi']:.1f}."
        ])
        if feature_df["current_meal_event"].iloc[0] == 1:
            contributing_factors.append("Active meal event recorded at latest timestamp.")
        if feature_df["steps_sum_past_15m"].iloc[0] > 100:
            contributing_factors.append(f"Elevated physical activity detected ({int(feature_df['steps_sum_past_15m'].iloc[0])} steps in past 15 min).")

        return {
            "status": "SUCCESS",
            "current_timestamp": current_time.strftime("%Y-%m-%d %H:%M:%S"),
            "predicted_target_timestamp": target_time.strftime("%Y-%m-%d %H:%M:%S"),
            "prediction_horizon_minutes": PREDICTION_HORIZON_MINUTES,
            "current_glucose_mg_dl": round(current_glucose, 1),
            "predicted_risk_class": predicted_class,
            "risk_label": RISK_CLASS_MAP.get(predicted_class, f"Class {predicted_class}"),
            "class_probabilities": prob_dict,
            "hypoglycemia_supported": False,
            "hypoglycemia_display_probability": "Not supported",
            "low_glucose_safety_alert": get_low_glucose_safety_alert(current_glucose, current_time.strftime("%Y-%m-%d %H:%M:%S")),
            "key_contributing_factors": contributing_factors,
            "safety_warning": SAFETY_WARNING,
            "unreliable_prediction_message": UNRELIABLE_PREDICTION_MESSAGE,
            "hypoglycemia_message": HYPOGLYCEMIA_UNSUPPORTED_STATEMENT,
            # Use model-version-aware warning (v1 keeps original exact text; v2 uses new text)
            "hypoglycemia_limitation": self.hypoglycemia_warning,
            "clinical_disclaimer": CLINICAL_PROTOTYPE_DISCLAIMER,
            "is_current_glucose_in_target": is_in_target,
            "current_glucose_caution": current_glucose_caution,
            "is_stale": is_stale,
            "input_features": feature_df.iloc[0].to_dict(),
            "active_model_version": self.active_model_version,
        }

    def simulate_what_if(
        self,
        baseline_profile: dict,
        recent_readings: pd.DataFrame,
        hypothetical_delta_glucose: float = 0.0,
        hypothetical_delta_steps: int = 0,
        scenario_description: str = "Hypothetical Scenario"
    ) -> dict:
        """
        What-If Counterfactual Simulation Interface:
        Compares observed model output against a clearly labeled hypothetical change.
        Guarantees source data is NOT mutated.
        """
        # Baseline observed prediction
        observed_result = self.predict_risk(baseline_profile, recent_readings)

        # Isolated deep copy for hypothetical alteration
        hypothetical_readings = recent_readings.copy(deep=True)

        # Apply hypothetical modifications strictly to copy
        if hypothetical_delta_glucose != 0.0:
            # Adjust the latest reading to reflect hypothetical trajectory
            hypothetical_readings.loc[hypothetical_readings.index[-1], "glucose_mg_dl"] = float(
                np.clip(
                    hypothetical_readings["glucose_mg_dl"].iloc[-1] + hypothetical_delta_glucose,
                    40.0,
                    400.0
                )
            )

        if hypothetical_delta_steps != 0:
            hypothetical_readings.loc[hypothetical_readings.index[-1], "steps"] = int(
                max(0, hypothetical_readings["steps"].iloc[-1] + hypothetical_delta_steps)
            )

        hypothetical_result = self.predict_risk(baseline_profile, hypothetical_readings)

        risk_changed = (observed_result["predicted_risk_class"] != hypothetical_result["predicted_risk_class"])

        return {
            "scenario_description": scenario_description,
            "is_hypothetical_simulation": True,
            "hypothetical_adjustments": {
                "delta_glucose_mg_dl": hypothetical_delta_glucose,
                "delta_steps": hypothetical_delta_steps
            },
            "observed_result": {
                "glucose_mg_dl": observed_result["current_glucose_mg_dl"],
                "risk_class": observed_result["predicted_risk_class"],
                "risk_label": observed_result["risk_label"],
                "probabilities": observed_result["class_probabilities"],
                "hypoglycemia_supported": False,
                "hypoglycemia_display_probability": "Not supported",
                "low_glucose_safety_alert": observed_result.get("low_glucose_safety_alert")
            },
            "hypothetical_result": {
                "glucose_mg_dl": hypothetical_result["current_glucose_mg_dl"],
                "risk_class": hypothetical_result["predicted_risk_class"],
                "risk_label": hypothetical_result["risk_label"],
                "probabilities": hypothetical_result["class_probabilities"],
                "hypoglycemia_supported": False,
                "hypoglycemia_display_probability": "Not supported",
                "is_simulated": True,
                "low_glucose_safety_alert": None  # Hypothetical value must NOT trigger measured-glucose alert
            },
            "risk_status_changed": risk_changed,
            "simulation_notice": (
                "HYPOTHETICAL SIMULATION NOTICE: This is a synthetic what-if sensitivity analysis. "
                "It does NOT model true physiological response kinetics and is strictly NOT medical advice."
            ),
            "safety_warning": SAFETY_WARNING,
            "hypoglycemia_message": HYPOGLYCEMIA_UNSUPPORTED_STATEMENT,
            # Use model-version-aware warning
            "hypoglycemia_limitation": self.hypoglycemia_warning,
            "clinical_disclaimer": CLINICAL_PROTOTYPE_DISCLAIMER,
            "active_model_version": self.active_model_version,
        }


# Module-level convenience functions
_engine_singleton = None


def get_engine() -> TwinEngine:
    global _engine_singleton
    if _engine_singleton is None:
        _engine_singleton = TwinEngine()
    return _engine_singleton


def predict_patient_risk(baseline_profile: dict, recent_readings: pd.DataFrame) -> dict:
    return get_engine().predict_risk(baseline_profile, recent_readings)


def simulate_what_if(
    baseline_profile: dict,
    recent_readings: pd.DataFrame,
    hypothetical_delta_glucose: float = 0.0,
    hypothetical_delta_steps: int = 0,
    scenario_description: str = "Hypothetical Scenario"
) -> dict:
    return get_engine().simulate_what_if(
        baseline_profile,
        recent_readings,
        hypothetical_delta_glucose,
        hypothetical_delta_steps,
        scenario_description
    )
