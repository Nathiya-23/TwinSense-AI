# Filename helper
# ---------------------------------------------------------------------------
def safe_report_filename(patient_id: str, extension: str) -> str:
    """
    Returns a safe, timestamped report filename.
    The patient_id is sanitised so it cannot traverse the filesystem.
    """
    safe_pid = re.sub(r"[^A-Za-z0-9_\-]", "_", patient_id)
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    return f"TwinSense_Report_{safe_pid}_{ts}.{extension}"


