def get_latest_prediction_for_patient(
    patient_id: str,
    prediction_id: Optional[int] = None,
    db_path: Optional[Path] = None,
) -> dict:
    """
    Returns a single prediction dict for *patient_id*.

    If *prediction_id* is provided:
      - Validates that the prediction exists (HTTP 404 if missing).
      - Validates that the prediction belongs to *patient_id* (HTTP 409 if mismatched).
    Otherwise returns the most recent prediction for the patient (HTTP 404 if none).
    """
    if not re.match(r"^[A-Za-z0-9_\-]+$", patient_id):
        raise HTTPException(status_code=400, detail="Invalid patient_id format.")

    conn = get_db_connection(db_path)
    cursor = conn.cursor()

    if prediction_id is not None:
        cursor.execute(
            """
            SELECT id, patient_id, prediction_timestamp, reading_timestamp,
                   predicted_target_timestamp, prediction_horizon_minutes,
                   current_glucose_mg_dl, predicted_risk_class, risk_label,
                   probabilities_json, contributing_factors_json
            FROM predictions
            WHERE id = ?
            """,
            (prediction_id,),
        )
        row = cursor.fetchone()
        conn.close()

        if row is None:
            raise HTTPException(
                status_code=404,
                detail=f"Prediction ID {prediction_id} not found."
            )

        if row["patient_id"] != patient_id:
            raise HTTPException(
                status_code=409,
                detail=(
                    f"Mismatched pair: Prediction ID {prediction_id} belongs to patient "
                    f"'{row['patient_id']}', not '{patient_id}'."
                )
            )
    else:
        cursor.execute(
            """
            SELECT id, patient_id, prediction_timestamp, reading_timestamp,
                   predicted_target_timestamp, prediction_horizon_minutes,
                   current_glucose_mg_dl, predicted_risk_class, risk_label,
                   probabilities_json, contributing_factors_json
            FROM predictions
            WHERE patient_id = ?
            ORDER BY id DESC
            LIMIT 1
            """,
            (patient_id,),
        )
        row = cursor.fetchone()
        conn.close()

        if row is None:
            raise HTTPException(
                status_code=404,
                detail=(
                    f"No prediction found for patient '{patient_id}'. "
                    "Please run a forecast first from the dashboard."
                )
            )

    d = dict(row)
    d["probabilities"] = json.loads(d.pop("probabilities_json", "{}") or "{}")
    d["contributing_factors"] = json.loads(
        d.pop("contributing_factors_json", "[]") or "[]"
    )
    return d


