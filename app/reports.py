# CSV generation
# ---------------------------------------------------------------------------
def generate_csv_report(profile: dict, prediction: dict) -> str:
    """
    Returns a UTF-8 CSV string containing the full prediction report.

    Uses csv.writer so commas, quotes, and newlines are properly escaped.
    Applies sanitize_csv_cell to neutralize formula injection on text cells.
    """
    output = io.StringIO()
    writer = csv.writer(output, quoting=csv.QUOTE_ALL, lineterminator="\r\n")

    def section(title: str):
        writer.writerow([])
        writer.writerow([f"=== {title} ==="])

    def write_kv(key: str, val):
        writer.writerow([sanitize_csv_cell(key), sanitize_csv_cell(val)])

    # A. Report Information
    section("REPORT INFORMATION")
    write_kv("Report Title", REPORT_TITLE)
    write_kv("Generated At", datetime.now().strftime("%Y-%m-%d %H:%M:%S"))
    write_kv("Model Name", MODEL_NAME)
    write_kv("Prediction Horizon", PREDICTION_HORIZON)
    write_kv("Data Classification", SYNTHETIC_LABEL)
    write_kv("Prediction Identity Strategy", IDENTITY_STRATEGY)

    # B. Patient Information
    section("PATIENT INFORMATION")
    write_kv("Synthetic Patient ID", profile.get("patient_id"))
    write_kv("Diabetes Type", profile.get("diabetes_type"))
    write_kv("Age", profile.get("age"))
    write_kv("BMI", profile.get("bmi"))
    write_kv("Baseline HbA1c (%)", profile.get("baseline_hba1c"))
    write_kv("Diabetes Duration (years)", profile.get("diabetes_duration_years"))

    # C. Prediction Information
    section("PREDICTION INFORMATION")
    write_kv("Prediction ID", prediction.get("id"))
    write_kv("Prediction Generated At", prediction.get("prediction_timestamp"))
    write_kv("Observation Timestamp (Reading)", prediction.get("reading_timestamp"))
    write_kv("Target Timestamp (45 Minutes Later)", prediction.get("predicted_target_timestamp"))
    write_kv("Current Observed Glucose (mg/dL)", prediction.get("current_glucose_mg_dl"))
    write_kv("Predicted Risk Class", prediction.get("predicted_risk_class"))
    write_kv("Risk Label", prediction.get("risk_label"))

    # Probabilities
    section("MODEL-ESTIMATED CLASS PROBABILITIES (Synthetic Data Only)")
    writer.writerow(
        ["NOTE", sanitize_csv_cell("Percentages represent model-estimated class probabilities on synthetic data only.")]
    )
    writer.writerow(
        ["NOTE", sanitize_csv_cell("These are NOT clinical risk percentages and are not clinically validated.")]
    )
    probs: dict = prediction.get("probabilities", {}) or {}
    for class_key, raw_prob in probs.items():
        if "hypo" in str(class_key).lower() or str(class_key).startswith("1"):
            pct = "Not supported"
        else:
            try:
                pct = f"{round(float(raw_prob) * 100, 2):.2f}%"
            except (TypeError, ValueError):
                pct = "Not available"
        writer.writerow([sanitize_csv_cell(f"Class probability - {class_key}"), pct])
    if not probs:
        writer.writerow(["Class probabilities", "Not available"])

    # Low-glucose safety alert (strictly based on measured reading, not ML prediction)
    obs_glucose = prediction.get("current_glucose_mg_dl")
    obs_timestamp = prediction.get("reading_timestamp") or prediction.get("observation_timestamp") or prediction.get("prediction_timestamp")
    from src.twin_engine import get_low_glucose_safety_alert
    low_glucose_alert = get_low_glucose_safety_alert(obs_glucose, obs_timestamp)
    if low_glucose_alert:
        section("LOW-GLUCOSE SAFETY ALERT (MEASURED READING)")
        writer.writerow(["LOW GLUCOSE SAFETY ALERT", sanitize_csv_cell(low_glucose_alert)])

    # Contributing factors
    section("KEY CONTRIBUTING FACTORS (Past 30 Minutes)")
    factors: list = prediction.get("contributing_factors", []) or []
    if factors:
        for i, factor in enumerate(factors, start=1):
            writer.writerow([sanitize_csv_cell(f"Factor {i}"), sanitize_csv_cell(factor)])
    else:
        writer.writerow(["Contributing Factors", "Not available"])

    # Model warnings
    section("MODEL WARNINGS")
    active_warning = get_active_hypoglycemia_warning(prediction)
    write_kv("Hypoglycemia Limitation", active_warning)

    # General Suggestions
    section("GENERAL SUGGESTIONS")
    from app.suggestions import get_suggestions_for_risk_class
    sugg_data = get_suggestions_for_risk_class(
        prediction.get("predicted_risk_class"),
        current_glucose=prediction.get("current_glucose_mg_dl")
    )
    write_kv("Suggestions Disclaimer", sugg_data["disclaimer"])
    write_kv("Hypoglycemia Limitation Note", sugg_data["hypoglycemia_note"])
    if sugg_data.get("why_am_i_seeing_this"):
        write_kv("Basis for Suggestions", sugg_data["why_am_i_seeing_this"])
    for i, s in enumerate(sugg_data["suggestions"], start=1):
        write_kv(f"Suggestion {i}", s)

    # D. Mandatory Disclaimer & Safety Limitations
    section("MANDATORY DISCLAIMER")
    writer.writerow(["MANDATORY DISCLAIMER", sanitize_csv_cell(MANDATORY_DISCLAIMER)])

    section("MANDATORY SAFETY LIMITATIONS")
    for i, statement in enumerate(SAFETY_STATEMENTS, start=1):
        writer.writerow([sanitize_csv_cell(f"Safety Statement {i}"), sanitize_csv_cell(statement)])

    return output.getvalue()


