# ---------------------------------------------------------------------------
# CSV Cell Sanitization (Neutralize Formula Injection)
# ---------------------------------------------------------------------------
def sanitize_csv_cell(val):
    """
    Neutralizes formula injection in CSV cells.
    Any text cell starting with =, +, -, or @ gets a leading apostrophe.
    Numeric values (int, float, or purely numeric strings) are unaltered.
    Missing/empty values default to 'Not available'.
    """
    if val is None or val == "":
        return "Not available"
    if isinstance(val, (int, float)):
        return val
    s = str(val)
    # Check if string represents a pure numeric value (do not alter numeric values)
    try:
        float(s)
        return val
    except ValueError:
        pass
    if s and s[0] in ("=", "+", "-", "@"):
        return "'" + s
    return s


